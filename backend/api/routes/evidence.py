from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session
from sqlalchemy import desc
from typing import List

from backend.event_store.database import get_db
from backend.event_store.models import AgentAuditLogModel
from backend.api.middleware.access_control import get_current_staff

router = APIRouter(prefix="/evidence", tags=["evidence"])

@router.get("/")
def get_evidence_export(
    db: Session = Depends(get_db),
    current_user: dict = Depends(get_current_staff)
):
    """
    Returns structured evidence and CAPA drafts generated by the Evidence Agent.
    """
    logs = db.query(AgentAuditLogModel).filter(
        AgentAuditLogModel.agent_name == "EvidenceAgent",
        AgentAuditLogModel.action == "draft_capa"
    ).order_by(desc(AgentAuditLogModel.timestamp)).all()
    
    results = []
    for log in logs:
        input_state = log.input_state or {}
        output = log.output_decision or {}
        
        results.append({
            "event_id": log.event_id,
            "patient_id": input_state.get("patient_id"),
            "ward_id": input_state.get("ward_id"),
            "rule_id": input_state.get("rule_id"),
            "nabh_chapter": output.get("nabh_mapping", {}).get("chapter"),
            "nabh_element": output.get("nabh_mapping", {}).get("element"),
            "capa_draft": output.get("capa_draft"),
            "model_version": log.model_or_rule_version,
            "timestamp": log.timestamp.isoformat() if log.timestamp else None
        })
        
    return results

@router.post("/generate")
def generate_evidence(
    db: Session = Depends(get_db),
    current_user: dict = Depends(get_current_staff)
):
    """
    Manually triggers the Evidence Agent to process closed gaps.
    """
    from backend.orchestration.evidence_agent.agent import EvidenceAgent
    agent = EvidenceAgent()
    agent.process_closed_gaps(db)
    return {"status": "success"}
